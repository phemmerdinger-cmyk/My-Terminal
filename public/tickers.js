// Rank: exact symbol > symbol starts with > name word starts with > contains
window.localSearch = function(q, n=10){
  q=String(q||"").trim().toUpperCase(); if(!q) return [];
  const qs=q.replace(/-USD$/,"");
  const scored=[];
  for(const [s,name,type] of window.TICKERS){
    const S=s.toUpperCase(), base=S.replace(/-USD$/,""), N=name.toUpperCase();
    let sc=0;
    if(S===q||base===qs) sc=100; else if(base.startsWith(qs)) sc=80; else if(N.startsWith(q)) sc=60; else if(N.split(/[\s.&/-]+/).some(w=>w.startsWith(q))) sc=45; else if(N.includes(q)) sc=20;
    if(sc) scored.push({symbol:s,name,typeDisp:type,score:sc,i:scored.length});
  }
  return scored.sort((a,b)=>b.score-a.score||a.i-b.i).slice(0,n);
};
